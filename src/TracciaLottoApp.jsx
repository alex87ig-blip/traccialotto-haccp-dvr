function MultiDocArchiveSection({ title, subtitle, docs, onAddDocs, onDeleteDoc, triggerUniversalPrint }) {
  return (
    <div className="bg-white rounded-2xl border border-slate-200 p-5 shadow-sm space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h3 className="font-extrabold text-base">{title}</h3>
          <p className="text-xs text-slate-500">{subtitle}</p>
        </div>
        <label className="bg-emerald-600 hover:bg-emerald-500 text-white px-4 py-2.5 rounded-xl text-xs font-bold flex items-center gap-2 cursor-pointer shadow">
          <Upload className="w-4 h-4" /> Carica Più File (PDF / Foto)
          <input
            type="file"
            multiple
            accept="image/*,application/pdf,.pdf"
            className="hidden"
            onChange={async (e) => {
              const files = Array.from(e.target.files || []);
              if (!files.length) return;
              const loaded = await Promise.all(
                files.map(
                  (f) =>
                    new Promise((res) => {
                      const reader = new FileReader();
                      reader.onload = () =>
                        res({
                          id: `doc-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
                          name: f.name,
                          type: f.type,
                          dataUrl: reader.result,
                          uploadedAt: new Date().toLocaleDateString('it-IT')
                        });
                      reader.readAsDataURL(f);
                    })
                )
              );
              onAddDocs(loaded);
            }}
          />
        </label>
      </div>

      {docs.length === 0 ? (
        <div className="p-8 border-2 border-dashed rounded-2xl text-center text-slate-400 text-xs">
          Nessun documento caricato. Usa il tasto verde per selezionare uno o più PDF/foto insieme.
        </div>
      ) : (
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-3">
          {docs.map((doc) => (
            <div key={doc.id} className="border rounded-xl p-3 bg-slate-50 flex flex-col justify-between gap-2">
              <div className="flex items-center justify-between gap-2">
                <div className="font-bold text-xs truncate">{doc.name}</div>
                <button onClick={() => onDeleteDoc(doc.id)} className="text-red-600 p-1 hover:bg-red-50 rounded">
                  <Trash2 className="w-4 h-4" />
                </button>
              </div>
              {doc.dataUrl && doc.type?.startsWith('image') && (
                <img src={doc.dataUrl} alt={doc.name} className="h-32 w-full object-cover rounded-lg border" />
              )}
              <div className="flex justify-between items-center text-[11px] text-slate-500 pt-1">
                <span>Caricato: {doc.uploadedAt}</span>
                <button
                  onClick={() =>
                    triggerUniversalPrint(
                      doc.name,
                      `<h2>${title}</h2><p>Documento: <strong>${doc.name}</strong> (${doc.uploadedAt})</p>${
                        doc.type?.startsWith('image') && doc.dataUrl
                          ? `<img src="${doc.dataUrl}" style="max-width:100%;margin-top:12px;" />`
                          : '<p>Documento PDF archiviato in piattaforma.</p>'
                      }`
                    )
                  }
                  className="text-blue-600 font-bold hover:underline flex items-center gap-1"
                >
                  <Printer className="w-3.5 h-3.5" /> Stampa
                </button>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
